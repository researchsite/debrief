import fs from 'fs';
import path from 'path';

const dir = 'fixtures/import';
fs.mkdirSync(dir, { recursive: true });

// A 1x1 white PNG (smallest valid PNG)
const PNG_1x1 = Buffer.from([
  0x89,0x50,0x4E,0x47,0x0D,0x0A,0x1A,0x0A, // PNG signature
  0x00,0x00,0x00,0x0D, // IHDR length
  0x49,0x48,0x44,0x52, // IHDR
  0x00,0x00,0x00,0x01, // width: 1
  0x00,0x00,0x00,0x01, // height: 1
  0x08,0x02,           // bit depth: 8, color type: 2 (RGB)
  0x00,0x00,0x00,     // compression, filter, interlace
  0x90,0x77,0x53,0xDE, // CRC
  0x00,0x00,0x00,0x0C, // IDAT length
  0x49,0x44,0x41,0x54, // IDAT
  0x08,0xD7,0x63,0xF8,0xFF,0xFF,0x3F,0x00,0x05,0xFE,0x02,0xFE, // compressed data
  0xDC,0xCC,0x59,0xE7, // CRC
  0x00,0x00,0x00,0x00, // IEND length
  0x49,0x45,0x4E,0x44, // IEND
  0xAE,0x42,0x60,0x82  // CRC
]);

fs.writeFileSync(path.join(dir, 'coupon.png'), PNG_1x1);
fs.writeFileSync(path.join(dir, 'slide.png'), PNG_1x1);
fs.writeFileSync(path.join(dir, 'business_card.png'), PNG_1x1);

